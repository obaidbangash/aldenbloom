      function getScaleForContainer(viewerEl, pageDefaultWidth) {
        if (!viewerEl || pageDefaultWidth <= 0) return 1.2;
        var w = viewerEl.clientWidth || 400;
        return Math.max((w - 24) / pageDefaultWidth, 0.5);
      }

      function renderPdf(modalId) {
        var cfg = pdfConfig[modalId];
        if (!cfg) return;
        var viewerEl = document.getElementById(viewerId(modalId));
        var loadingEl = document.getElementById(loadingId(modalId));
        if (!viewerEl || !loadingEl) return;
